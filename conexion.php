<?php

/*
|--------------------------------------------------------------------------
| ZONA HORARIA DEL SISTEMA
|--------------------------------------------------------------------------
*/

date_default_timezone_set('America/La_Paz');


/*
|--------------------------------------------------------------------------
| VARIABLES DE ENTORNO
|--------------------------------------------------------------------------
*/

$env = parse_ini_file(".env");

$host = $env["DB_HOST"];
$user = $env["DB_USER"];
$pass = $env["DB_PASS"];
$db   = $env["DB_NAME"];


/*
|--------------------------------------------------------------------------
| CONEXIÓN MYSQL
|--------------------------------------------------------------------------
*/

$conn = new mysqli(
    $host,
    $user,
    $pass,
    $db
);

if ($conn->connect_error) {

    die(
        "Error de conexión: " .
        $conn->connect_error
    );
}


/*
|--------------------------------------------------------------------------
| CODIFICACIÓN
|--------------------------------------------------------------------------
*/

$conn->set_charset("utf8mb4");


/*
|--------------------------------------------------------------------------
| ZONA HORARIA MYSQL PARA ESTA CONEXIÓN
|--------------------------------------------------------------------------
|
| Bolivia utiliza UTC-4 durante todo el año.
|
*/

$conn->query(
    "SET time_zone = '-04:00'"
);

?>